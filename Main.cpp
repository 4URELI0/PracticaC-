#include <bits/stdc++.h>
using namespace std;

int main(int argc, char const *argv[])
{
    /*FUNCION PREINCREMENTO*/
    //Primero se realiza el incremento y luego la asignacion
    int a = 1;
    int b = ++a;

    cout <<"El valor de a: "<< a << endl;
    cout <<"El valor de b: "<< b << endl;
    return 0;
}